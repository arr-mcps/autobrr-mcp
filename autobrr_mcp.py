# autobrr responses are JSON, except healthz (text/plain) and the feed "latest
# run" payload (raw string). `dict[str, Any]` (not bare `Any`) matters here:
# FastMCP needs a concrete schema to build MCP structured content, and skips
# that step entirely for an `Any` return type -- which silently makes
# Client.call_tool's `.data` come back None for any tool returning a JSON array.
JSONObj = dict[str, Any]
JSONVal = JSONObj | list[Any] | str

mcp = FastMCP("autobrr-mcp")

_client: httpx.AsyncClient | None = None


def build_client(
    base_url: str, api_key: str | None, transport: httpx.BaseTransport | None = None
) -> httpx.AsyncClient:
    """Client pinned to the origin (no path suffix) so registered full paths
    like /api/filters resolve correctly via httpx base join."""
    headers = {"X-API-Token": api_key} if api_key else {}
    return httpx.AsyncClient(base_url=f"{base_url.rstrip('/')}", headers=headers, transport=transport)


async def _req(
    method: str,
    path: str,
    params: dict[str, Any] | None = None,
    json_body: JSONVal | None = None,
) -> JSONVal:
    assert _client is not None, "client not configured"
    r = await _client.request(method, path, params=params, json=json_body)
    if r.status_code >= 400:
        try:
            msg = r.json().get("message", r.text)
        except ValueError:
            msg = r.text
        raise ToolError(f"autobrr API {r.status_code}: {msg}")
    if not r.text:
        return {}
    try:
        return r.json()
    except ValueError:
        return r.text


def _omit(params: dict[str, Any]) -> dict[str, Any]:
    """Drop keys whose values are empty/None/empty-collection so the API's
    defaults apply."""
    return {k: v for k, v in params.items() if v not in ("", None) and not (isinstance(v, (list, dict)) and not v)}


