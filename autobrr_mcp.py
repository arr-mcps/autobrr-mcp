"""MCP server exposing autobrr's REST API (Go, chi router; no OpenAPI spec) as tools.

Full coverage of autobrr's JSON-producing /api endpoints (every handler in
autobrr's internal/http), read and write, but exposed as 13 resource-scoped
*portmanteau* tools instead of one tool per endpoint. Each portmanteau tool
(e.g. autobrr_filters, autobrr_release) takes an `operation` enum plus an
`arguments` dict; see AGENTS.md for the rationale (a ~100+-tool server blows
the MCP context budget on session start).

The endpoint table is hand-written from autobrr's `internal/http/<resource>.go`
handler `Routes` methods (develop HEAD). autobrr publishes no OpenAPI spec, so
unlike sonarr-mcp there is no vendored spec to diff against. `_TOOL_REGISTRY`
below lists every endpoint; `_GROUPS` buckets them by resource, and
`register_tools` registers one dispatching tool per group that calls the right
function by name. Nothing about the endpoint functions themselves changes --
grouping is purely a registration-time concern.

Auth is the X-API-Token header, created in autobrr Settings > API Keys (also
accepted as `?apikey=` or a session cookie, but the header is what an MCP
client uses). A group tool is marked readOnlyHint=True only when every
operation in it is a GET; mixed groups carry no hints (writes still get a
`WRITE:` / `DESTRUCTIVE:` note in their operation's doc line). Bodies are
passed as opaque dicts/lists. build_client points at the origin with no path
suffix so httpx joins the fully-qualified /api/... paths correctly.

Excluded on purpose: /auth (session/OIDC, not usable over an API token),
/events (SSE stream, not JSON), the inbound /webhook list-trigger routes
(same job as /lists/refresh), and /logs/files/{logFile} (raw text download).
Healthz endpoints return text/plain ("OK") rather than JSON, and /feeds/{id}/
latest returns a raw string body -- _req falls back to returning the text, so
those operations legitimately return `str` and dispatch is typed JSONVal | str.
"""

